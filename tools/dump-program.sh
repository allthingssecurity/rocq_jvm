#!/usr/bin/env bash
# Dump every .class under <classdir> into theories/Classes/<Prefix>_<Class>.v and write
# theories/Classes/<Prefix>.v with  Definition files : list (list Z)  (all of them, sorted by path).
#   tools/dump-program.sh <classdir> <Prefix>
set -euo pipefail
cd "$(dirname "$0")/.."
dir=$1; pre=$2
mods=()
while read -r f; do
  rel=${f#$dir/}; base=$(echo "${rel%.class}" | sed 's|.*/||; s|\$|_|g')
  mod="${pre}_${base}"
  python3 tools/classdump.py "$f" "theories/Classes/$mod.v" "$dir/BUILD-INFO"
  mods+=("$mod")
done < <(find "$dir" -name '*.class' | sort)
{
  echo "(* Generated by tools/dump-program.sh $dir $pre -- do not edit. *)"
  echo "From Stdlib Require Import ZArith List."
  echo "Import ListNotations."
  echo "From JVM.Classes Require ${mods[*]}."
  echo "Definition files : list (list Z) := ["
  sep=" "
  for m in "${mods[@]}"; do echo "  $sep$m.bytes"; sep=";"; done
  echo "]."
} > "theories/Classes/$pre.v"
for m in "${mods[@]}"; do echo "theories/Classes/$m.v"; done
echo "theories/Classes/$pre.v"
