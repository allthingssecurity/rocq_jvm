import java.lang.reflect.*; import java.util.*;
public class GenJdkTables {
  static String d(Class<?> c){ if(c==int.class)return "I"; if(c==long.class)return "J"; if(c==boolean.class)return "Z"; if(c==byte.class)return "B"; if(c==char.class)return "C"; if(c==short.class)return "S"; if(c==float.class)return "F"; if(c==double.class)return "D"; if(c==void.class)return "V"; if(c.isArray())return c.getName().replace('.','/'); return "L"+c.getName().replace('.','/')+";"; }
  static String q(String s){ return "\""+s+"\""; }
  public static void main(String[] a) throws Exception {
    StringBuilder sb = new StringBuilder();
    sb.append("(** * Declared members of the JDK classes and interfaces the machine reasons about without loading them.\n");
    sb.append("    GENERATED by tools/gen_jdk_tables.sh (reflection on JDK ").append(System.getProperty("java.version")).append("); do not edit.\n");
    sb.append("    Used by method/field resolution and selection (JVMS 5.4.3, 5.4.6) when a lookup reaches a\n");
    sb.append("    JDK class: an entry lists every declared method/field (any access) as (name, descriptor, access_flags). *)\n");
    sb.append("From Stdlib Require Import ZArith String List.\nImport ListNotations.\nOpen Scope string_scope.\nOpen Scope Z_scope.\n\n");
    sb.append("Record jinfo := mkji { ji_access : Z; ji_super : option string; ji_ifaces : list string;\n  ji_methods : list (string * string * Z); ji_fields : list (string * string * Z) }.\n\n");
    sb.append("Definition jdk_table : list (string * jinfo) := [\n");
    StringJoiner all = new StringJoiner(";\n");
    for (String n : a) {
      Class<?> c = Class.forName(n.replace('/','.'));
      StringBuilder e = new StringBuilder();
      int cacc = c.getModifiers() & 0xffff;
      String sup = c.isInterface() ? "Some \"java/lang/Object\"" : (c.getSuperclass()==null?"None":"Some "+q(c.getSuperclass().getName().replace('.','/')));
      e.append("  (").append(q(n)).append(", mkji ").append(cacc).append(" (").append(sup).append(") [");
      StringJoiner ij = new StringJoiner("; "); for (Class<?> i : c.getInterfaces()) ij.add(q(i.getName().replace('.','/'))); e.append(ij).append("]\n    [");
      StringJoiner mj = new StringJoiner(";\n     ");
      Method[] ms = c.getDeclaredMethods(); Arrays.sort(ms, Comparator.comparing(Method::toString));
      for (Method m : ms) { StringBuilder ds = new StringBuilder("("); for (Class<?> p : m.getParameterTypes()) ds.append(d(p)); ds.append(")").append(d(m.getReturnType()));
        int acc = m.getModifiers() & 0xfff; if (m.isBridge()) acc |= 0x40; if (m.isSynthetic()) acc |= 0x1000; if (m.isVarArgs()) acc |= 0x80;
        mj.add("(" + q(m.getName()) + ", " + q(ds.toString()) + ", " + acc + ")"); }
      e.append(mj).append("]\n    [");
      StringJoiner fj = new StringJoiner("; ");
      for (Field f : c.getDeclaredFields()) fj.add("(" + q(f.getName()) + ", " + q(d(f.getType())) + ", " + (f.getModifiers()&0xffff) + ")");
      e.append(fj).append("])");
      all.add(e.toString());
    }
    sb.append(all).append("].\n\n");
    sb.append("Fixpoint jdk_lookup (l : list (string * jinfo)) (c : string) : option jinfo :=\n  match l with\n  | nil => None\n  | (n, j) :: r => if String.eqb n c then Some j else jdk_lookup r c\n  end.\n\n");
    sb.append("Definition jdk_info (c : string) : option jinfo := jdk_lookup jdk_table c.\n");
    System.out.print(sb);
  }
}
