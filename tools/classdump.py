#!/usr/bin/env python3
"""Copy the bytes of a .class file into a Rocq module, verbatim, as a hex string.

    tools/classdump.py <file.class> <Out.v> [BUILD-INFO]

This is the only part of the loader outside Rocq. It does not interpret the
class file at all: the generated module contains the file's bytes as lowercase
hex (two characters per byte, no separators), its SHA-256 and its provenance.
Parsing and decoding happen in Rocq (theories/Loader/ClassFile.v).
tools/check-dumps.sh re-derives the hex from the .class files and compares.
"""
import hashlib, sys, os

def main():
    src, out = sys.argv[1], sys.argv[2]
    info = sys.argv[3] if len(sys.argv) > 3 else None
    data = open(src, 'rb').read()
    h = hashlib.sha256(data).hexdigest()
    hexs = data.hex()
    prov = []
    if info and os.path.exists(info):
        for line in open(info):
            if line.startswith(('label:', 'commit:', 'module:', 'javac:', 'remote')):
                prov.append(line.rstrip())
    lines = ["(* Generated by tools/classdump.py -- do not edit.",
             "   file:   " + src,
             "   sha256: " + h,
             "   bytes:  %d" % len(data)] + ["   " + p for p in prov] + ["*)",
             "From Stdlib Require Import String ZArith List.",
             "From JVM.Loader Require Import Hex.",
             "",
             'Definition sha256 : string := "%s".' % h,
             "Definition size : nat := %d." % len(data),
             "Definition hex : string :="]
    # split the hex into 64-byte chunks joined with ++ to keep lines short
    chunks = [hexs[i:i + 128] for i in range(0, len(hexs), 128)] or [""]
    body = "  (" + "\n   ++ ".join('"%s"' % c for c in chunks) + ")%string."
    lines.append(body)
    lines.append("Definition bytes : list Z := hex_to_bytes hex.")
    open(out, 'w').write("\n".join(lines) + "\n")

if __name__ == '__main__':
    main()
